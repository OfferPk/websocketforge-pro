  'use strict';

  function generateNodeWs(cfg) {
    const port = cfg.port || 443;
    const origins = cfg.allowed_origins || ['https://app.example.com'];
    const maxPayload = cfg.max_payload_bytes || 65536;

    return `/**
 * =========================================================================
 * Node.js (ws v8+) Production Hardened WebSocket Server
 * Generated by WebSocketForge Pro (v1.0.0) - Zero-Trust Verified
 * =========================================================================
 */

const { WebSocketServer } = require('ws');
const https = require('https');
const fs = require('fs');

const ALLOWED_ORIGINS = new Set(${JSON.stringify(origins)});
const MAX_PAYLOAD_BYTES = ${maxPayload};

// TLS 1.3 HTTPS Server
const server = https.createServer({
    cert: fs.readFileSync('/etc/ssl/certs/server.crt'),
    key: fs.readFileSync('/etc/ssl/private/server.key'),
    minVersion: 'TLSv1.3'
});

const wss = new WebSocketServer({
    server,
    maxPayload: MAX_PAYLOAD_BYTES,
    verifyClient: (info, callback) => {
        const origin = info.origin;
        // 1. Strict CSWSH Origin Validation
        if (!origin || !ALLOWED_ORIGINS.has(origin)) {
            console.warn(\`[CSWSH BLOCKED] Unauthorized Origin: \${origin}\`);
            return callback(false, 403, 'Forbidden: Untrusted Origin');
        }

        // 2. Pre-Upgrade Ticket/Token Validation
        const url = new URL(info.req.url, 'https://localhost');
        const token = url.searchParams.get('ticket');
        if (!token) {
            console.warn('[AUTH BLOCKED] Missing authentication ticket');
            return callback(false, 401, 'Unauthorized: Missing Ticket');
        }

        return callback(true);
    }
});

wss.on('connection', (ws, req) => {
    ws.isAlive = true;
    ws.on('pong', () => { ws.isAlive = true; });

    console.log(\`[+] Client connected from \${req.socket.remoteAddress}\`);

    ws.on('message', (data, isBinary) => {
        if (!isBinary) {
            console.log('[Message Received]:', data.toString());
            // Broadcast or process telemetry
            ws.send(JSON.stringify({ status: 'ACK', time: Date.now() }));
        }
    });

    ws.on('close', (code, reason) => {
        console.log(\`[-] Client disconnected. Code: \${code}, Reason: \${reason.toString()}\`);
    });
});

// Active Ping/Pong Keep-Alive Interval (Prunes Dead Sockets)
const heartbeatInterval = setInterval(() => {
    wss.clients.forEach(ws => {
        if (!ws.isAlive) {
            console.warn('[Heartbeat] Pruning unresponsive dead socket');
            return ws.terminate();
        }
        ws.isAlive = false;
        ws.ping();
    });
}, ${(cfg.ping_interval_sec || 30) * 1000});

wss.on('close', () => clearInterval(heartbeatInterval));

server.listen(${port}, () => {
    console.log(\`[+] WebSocket Server active on wss://0.0.0.0:${port}\`);
});
`;
  }

  function generatePythonWebsockets(cfg) {
    const port = cfg.port || 443;
    const origins = cfg.allowed_origins || ['https://app.example.com'];
    const maxPayload = cfg.max_payload_bytes || 65536;

    return `#!/usr/bin/env python3
# =========================================================================
# Python 3 (websockets v12+) Production Asynchronous Server
# Generated by WebSocketForge Pro (v1.0.0) - Zero-Trust Verified
# =========================================================================

import asyncio
import ssl
import json
import websockets

ALLOWED_ORIGINS = set(${JSON.stringify(origins)})
MAX_PAYLOAD_BYTES = ${maxPayload}

async def process_request(connection, request):
    """
    Validates Origin header during the HTTP Upgrade handshake (Anti-CSWSH)
    """
    origin = request.headers.get("Origin")
    if not origin or origin not in ALLOWED_ORIGINS:
        return connection.respond(
            websockets.http.StatusCodes.FORBIDDEN,
            f"Forbidden: Untrusted Origin '{origin}'\\n"
        )
    return None

async def handler(websocket):
    print(f"[+] Client connected from {websocket.remote_address}")
    try:
        async for message in websocket:
            data = json.loads(message)
            print(f"[Incoming]: {data}")
            await websocket.send(json.dumps({"status": "received", "timestamp": asyncio.get_event_loop().time()}))
    except websockets.exceptions.ConnectionClosed as e:
        print(f"[-] Connection closed: Code {e.code} ({e.reason})")

async def main():
    ssl_context = ssl.create_default_context(ssl.Purpose.CLIENT_AUTH)
    ssl_context.load_cert_chain(certfile="/etc/ssl/certs/server.crt", keyfile="/etc/ssl/private/server.key")
    ssl_context.minimum_version = ssl.TLSVersion.TLSv1_3

    async with websockets.serve(
        handler,
        "0.0.0.0",
        ${port},
        ssl=ssl_context,
        process_request=process_request,
        max_size=MAX_PAYLOAD_BYTES,
        ping_interval=${cfg.ping_interval_sec || 30},
        ping_timeout=${cfg.pong_timeout_sec || 10}
    ):
        print(f"[+] Python WebSocket Server listening on wss://0.0.0.0:${port}")
        await asyncio.get_running_loop().create_future()

if __name__ == "__main__":
    asyncio.run(main())
`;
  }

  function generateGoGorilla(cfg) {
    const port = cfg.port || 443;
    const origins = cfg.allowed_origins || ['https://app.example.com'];

    return `// =========================================================================
// Go (gorilla/websocket) Production Handler
// Generated by WebSocketForge Pro (v1.0.0) - Zero-Trust Verified
// =========================================================================

package main

import (
    "fmt"
    "log"
    "net/http"
    "time"
    "github.com/gorilla/websocket"
)

var allowedOrigins = map[string]bool{
${origins.map(o => `    "${o}": true,`).join('\n')}
}

var upgrader = websocket.Upgrader{
    ReadBufferSize:  1024,
    WriteBufferSize: 1024,
    // Strict Anti-CSWSH Origin Check
    CheckOrigin: func(r *http.Request) bool {
        origin := r.Header.Get("Origin")
        return allowedOrigins[origin]
    },
}

func wsHandler(w http.ResponseWriter, r *http.Request) {
    conn, err := upgrader.Upgrade(w, r, nil)
    if err != nil {
        log.Printf("Upgrade error: %v", err)
        return
    }
    defer conn.Close()

    conn.SetReadLimit(${cfg.max_payload_bytes || 65536})
    conn.SetReadDeadline(time.Now().Add(60 * time.Second))
    conn.SetPongHandler(func(string) error {
        conn.SetReadDeadline(time.Now().Add(60 * time.Second))
        return nil
    })

    for {
        msgType, msg, err := conn.ReadMessage()
        if err != nil {
            break
        }
        conn.WriteMessage(msgType, msg)
    }
}

func main() {
    http.HandleFunc("/ws", wsHandler)
    fmt.Printf("[+] Go WebSocket Server listening on :%d\\n", ${port})
    log.Fatal(http.ListenAndServeTLS(":${port}", "server.crt", "server.key", nil))
}
`;
  }

  function generateNginxConfig(cfg) {
    return `# =========================================================================
# NGINX Production WebSocket Reverse Proxy Configuration
# Generated by WebSocketForge Pro (v1.0.0) - Zero-Trust Verified
# =========================================================================

map $http_upgrade $connection_upgrade {
    default upgrade;
    ''      close;
}

upstream websocket_backend {
    server 127.0.0.1:8080;
    keepalive 32;
}

server {
    listen ${cfg.port || 443} ssl http2;
    server_name websocket.company-domain.com;

    ssl_certificate /etc/ssl/certs/fullchain.pem;
    ssl_certificate_key /etc/ssl/private/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;

    location /ws {
        # Forward WebSocket Upgrade Headers
        proxy_pass http://websocket_backend;
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;

        # Forward Client Metadata
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;

        # WebSocket Keep-Alive Timeouts (matches Ping/Pong)
        proxy_read_timeout 90s;
        proxy_send_timeout 90s;

        # Disable proxy buffering for real-time streaming
        proxy_buffering off;
    }
}
`;
  }

  return {
    generateNodeWs,
    generatePythonWebsockets,
    generateGoGorilla,
    generateNginxConfig
  };
